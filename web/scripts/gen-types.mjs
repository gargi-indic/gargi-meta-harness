import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { compile } from 'json-schema-to-typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const schemaPath = resolve(__dirname, '../src/generated/playbook.schema.json');
const outputPath = resolve(__dirname, '../src/generated/playbook.d.ts');

const schemaStr = readFileSync(schemaPath, 'utf-8');
const schema = JSON.parse(schemaStr);

compile(schema, "Playbook", {
  bannerComment: "/* Generated by web/scripts/gen-types.mjs from playbook.schema.json. Do not edit. */",
  additionalProperties: false,
  style: { singleQuote: false }
}).then(ts => {
  writeFileSync(outputPath, ts);
  console.log(`Generated ${outputPath}`);
}).catch(err => {
  console.error("Failed to generate types:", err);
  process.exit(1);
});
