import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { compile } from 'json-schema-to-typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const generated = resolve(__dirname, '../src/generated');

// [schema file, output file, root type name]
const targets = [
  ['playbook.schema.json', 'playbook.d.ts', 'Playbook'],
  ['proposal.schema.json', 'proposal.d.ts', 'ProposedPlan'],
];

try {
  for (const [schemaFile, outFile, name] of targets) {
    const schema = JSON.parse(readFileSync(resolve(generated, schemaFile), 'utf-8'));
    const ts = await compile(schema, name, {
      bannerComment: `/* Generated by web/scripts/gen-types.mjs from ${schemaFile}. Do not edit. */`,
      additionalProperties: false,
      style: { singleQuote: false },
    });
    const outputPath = resolve(generated, outFile);
    writeFileSync(outputPath, ts);
    console.log(`Generated ${outputPath}`);
  }
} catch (err) {
  console.error("Failed to generate types:", err);
  process.exit(1);
}
